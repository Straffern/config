local function opacity_step(delta)
	return hl.dsp.exec_cmd(string.format(
		[[n=$(hyprctl getprop active opacity | awk '{ n = $1 + %s; if (n < 0.1) n = 0.1; if (n > 1) n = 1; print n }'); hyprctl dispatch "hl.dsp.window.set_prop({ prop = 'opacity', value = '$n' })"]],
		delta
	))
end

-- Blur strength is global in Hyprland; only on/off is per-window.
local function blur_step(delta)
	return function()
		blur_size = math.max(1, math.min(20, blur_size + delta))
		hl.config({ decoration = { blur = { size = blur_size } } })
	end
end

